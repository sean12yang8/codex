import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH||'/usr/bin/chromium',headless:true,args:['--no-sandbox']});
const p=await browser.newPage({viewport:{width:1440,height:1050}});
const errors=[];p.on('pageerror',e=>errors.push(e.message));
try{
 await p.goto(process.env.BASE_URL||'http://127.0.0.1:8000');
 await p.getByLabel('工作邮箱').fill('demo@azure-lens.local');await p.getByLabel('密码',{exact:true}).fill('AzureLens-Demo-2026!');
 await p.getByRole('button',{name:'登录工作空间'}).click();await p.getByRole('heading',{name:'消费趋势'}).waitFor();
 const fixture=await p.evaluate(async()=>{
  const call=async(path,body)=>{const r=await fetch('/api/v1'+path,{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify(body)});if(!r.ok)throw Error('Fixture request failed '+path);return r.json()};
  const customer=await call('/customers',{name:'待核实成本验收 '+Date.now(),factor:'0.85',effective_date:new Date().toISOString().slice(0,10)});
  const tenant=await call('/tenants',{id:crypto.randomUUID(),customer_id:customer.id,name:'Source fixture tenant'});
  const sub=await call('/subscriptions',{id:crypto.randomUUID(),tenant_id:tenant.id,name:'Source fixture subscription'});
  const day=new Date(Date.now()-86400000).toISOString().slice(0,10);
  const form=new FormData();for(const [k,v] of Object.entries({subscription_id:sub.id,start:day,end:day,verified:'false',complete:'false',evidence:'Synthetic unverified-cost browser fixture'}))form.append(k,v);
  form.append('file',new Blob([`subscription_id,usage_date,service,currency,amount\n${sub.id},${day},Compute,USD,123.45\n${sub.id},${day},Storage,CNY,700\n`],{type:'text/csv'}),'unverified-source-fixture.csv');
  const r=await fetch('/api/v1/sync/imports',{method:'POST',body:form});if(!r.ok)throw Error('Fixture import failed');return {customerId:customer.id,day};
 });
 await p.reload();await p.getByRole('heading',{name:'消费趋势'}).waitFor();
 await p.getByLabel('客户筛选',{exact:true}).selectOption(fixture.customerId);
 await p.getByText('区间 ACR',{exact:true}).waitFor();
 await p.waitForFunction(()=>{const n=document.querySelector('.stat.highlight strong');return n&&n.textContent!=='—'});
 assert.notEqual(await p.locator('.stat').filter({hasText:'区间 ACR'}).locator('strong').innerText(),'—');
 assert.equal(await p.locator('.quality-banner,.trial-banner').count(),0);
 await p.getByRole('button',{name:'原始成本',exact:true}).click();
 await p.getByText('区间原始成本 · USD',{exact:true}).waitFor();
 const usd=p.locator('.stat').filter({hasText:'区间原始成本 · USD'});assert.match(await usd.innerText(),/123\.45/);
 assert.equal(await p.locator('.quality-banner,.trial-banner').count(),0);
 assert.equal(await p.getByRole('button',{name:'原始成本',exact:true}).getAttribute('aria-pressed'),'true');
 await p.locator('.rank-item').first().waitFor();await p.getByRole('heading',{name:'Azure 服务成本',exact:true}).waitFor();
 await p.getByLabel('原始成本币种').selectOption('CNY');
 assert.match(await p.locator('.stat').filter({hasText:'区间原始成本 · CNY'}).innerText(),/700\.00/);
 await p.getByLabel('趋势粒度').selectOption('month');await p.waitForResponse(r=>r.url().includes('/dashboard?')&&r.url().includes('granularity=month')&&r.status()===200);
 await p.getByRole('button',{name:'内部 ACR',exact:true}).click();
 await p.getByLabel('ACR 核验口径').selectOption('verified');
 const acr=p.locator('.stat').filter({hasText:'区间 ACR'});assert.equal(await acr.locator('strong').innerText(),'—');
 await p.getByText('当前没有可计入 ACR 的费用',{exact:true}).waitFor();
 await p.getByLabel('ACR 核验口径').selectOption('trial');
 await p.getByText('区间 ACR',{exact:true}).waitFor();
 await p.waitForFunction(()=>{const n=document.querySelector('.stat.highlight strong');return n&&n.textContent!=='—'});
 await fs.mkdir('/tmp/azure-lens-source-e2e',{recursive:true});
 await p.screenshot({path:'/tmp/azure-lens-source-e2e/dashboard.png',fullPage:true});
 await p.setViewportSize({width:390,height:844});
 assert.equal(await p.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true);
 await p.screenshot({path:'/tmp/azure-lens-source-e2e/mobile.png',fullPage:true});
 assert.deepEqual(errors,[]);
 console.log('PASS: unverified cost auto-display, native currency switch, source trend/top/services, ACR with unchanged discount backfill and streamlined labels, verified-only isolation, monthly filter and mobile.');
}finally{await browser.close()}
